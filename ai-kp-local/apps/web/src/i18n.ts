// 检测浏览器语言：zh-* 视为中文，其余视为英文。
export function detectUiLanguage(): string {
  if (typeof navigator === "undefined") return "zh-CN";
  const language = (navigator.language ?? "").toLowerCase();
  return language.startsWith("zh") ? "zh-CN" : "en-US";
}

